export function networkInfo(chainId: number) {
  const isMainnet = chainId === 31612
  return {
    chainImport: isMainnet ? "mezoMainnet" : "mezoTestnet",
    label: isMainnet ? "Mezo Mainnet" : "Mezo Testnet",
    explorer: isMainnet ? "https://explorer.mezo.org" : "https://explorer.test.mezo.org",
    isMainnet,
  }
}

/** npm-safe package name */
export function sanitizeProjectName(input: string): string {
  const cleaned = input
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^[._-]+/, "")
    .replace(/-+/g, "-")
    .replace(/-$/, "")
    .slice(0, 214)
  return cleaned || "mezo-dapp"
}

/** Safe for use inside a double-quoted JS/JSON string and in HTML text */
export function escapeText(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/</g, "&lt;").replace(/>/g, "&gt;")
}

