export function abiHelpersFile(): string {
  return `import { isAddress, isHex, type Abi, type AbiFunction, type AbiParameter } from "viem";

export function getFunctions(abi: Abi) {
  const functions = abi.filter((item): item is AbiFunction => item.type === "function");
  return {
    reads: functions.filter((f) => f.stateMutability === "view" || f.stateMutability === "pure"),
    writes: functions.filter((f) => f.stateMutability === "nonpayable" || f.stateMutability === "payable"),
  };
}

/** Unique key for a function (handles overloads) */
export function signature(fn: AbiFunction): string {
  return fn.name + "(" + fn.inputs.map((input) => input.type).join(",") + ")";
}

/** Whether an input is entered as JSON (arrays and tuples) */
export function isComplex(param: AbiParameter): boolean {
  return param.type.endsWith("]") || param.type.startsWith("tuple");
}

export function placeholderFor(param: AbiParameter): string {
  if (param.type.endsWith("]")) return "JSON array, e.g. [1, 2]";
  if (param.type.startsWith("tuple")) return "JSON object or array";
  if (param.type === "address") return "0x...";
  if (param.type === "bool") return "true or false";
  if (param.type.startsWith("bytes")) return "0x... (hex)";
  if (param.type.startsWith("uint") || param.type.startsWith("int")) return "Integer (wei for token amounts)";
  return param.type;
}

function label(param: AbiParameter): string {
  return (param.name || "argument") + " (" + param.type + ")";
}

function coerce(param: AbiParameter, value: unknown): unknown {
  const { type } = param;

  if (type.endsWith("]")) {
    if (!Array.isArray(value)) throw new Error(label(param) + " must be a JSON array");
    const inner = { ...param, type: type.slice(0, type.lastIndexOf("[")) } as AbiParameter;
    return value.map((item) => coerce(inner, item));
  }

  if (type.startsWith("tuple")) {
    const components = (param as { components?: readonly AbiParameter[] }).components ?? [];
    if (Array.isArray(value)) return components.map((c, i) => coerce(c, value[i]));
    if (value && typeof value === "object") {
      const record = value as Record<string, unknown>;
      return Object.fromEntries(components.map((c, i) => [c.name || String(i), coerce(c, record[c.name || String(i)])]));
    }
    throw new Error(label(param) + " must be a JSON object or array");
  }

  const text = typeof value === "string" ? value.trim() : String(value ?? "").trim();

  if (type.startsWith("uint") || type.startsWith("int")) {
    if (!/^-?\\d+$/.test(text)) throw new Error(label(param) + " must be a whole number");
    const n = BigInt(text);
    if (type.startsWith("uint") && n < BigInt(0)) throw new Error(label(param) + " cannot be negative");
    return n;
  }

  if (type === "bool") {
    if (value === true || text === "true" || text === "1") return true;
    if (value === false || text === "false" || text === "0") return false;
    throw new Error(label(param) + " must be true or false");
  }

  if (type === "address") {
    if (!isAddress(text)) throw new Error(label(param) + " is not a valid address");
    return text;
  }

  if (type.startsWith("bytes")) {
    if (!isHex(text)) throw new Error(label(param) + " must be 0x-prefixed hex");
    return text;
  }

  return typeof value === "string" ? value : text;
}

/** Turn raw form strings into typed arguments for viem */
export function parseArgs(fn: AbiFunction, raw: Record<string, string>): unknown[] {
  return fn.inputs.map((param, index) => {
    const key = String(index);
    const value = raw[key] ?? "";
    if (isComplex(param)) {
      if (!value.trim()) throw new Error(label(param) + " is required");
      let parsed: unknown;
      try {
        parsed = JSON.parse(value);
      } catch {
        throw new Error(label(param) + " must be valid JSON");
      }
      return coerce(param, parsed);
    }
    if (!value.trim() && param.type !== "string") throw new Error(label(param) + " is required");
    return coerce(param, value);
  });
}

/** Pretty-print any return value (bigint-safe) */
export function formatResult(value: unknown): string {
  if (value === undefined) return "—";
  if (typeof value === "bigint") return value.toString();
  if (typeof value === "string") return value;
  return JSON.stringify(value, (_key, v) => (typeof v === "bigint" ? v.toString() : v), 2);
}

/** Human-readable error from viem / wagmi / wallets */
export function errorMessage(error: unknown): string {
  if (error && typeof error === "object") {
    const e = error as { shortMessage?: string; details?: string; message?: string };
    if (e.shortMessage) {
      const short = e.shortMessage.replace(/\\s*\\n+\\s*/g, " ");
      // Revert reasons are already in shortMessage; otherwise add the RPC details
      return e.details && !/reason:/i.test(short) ? short + " (" + e.details + ")" : short;
    }
    if (e.message) return e.message.split("\\n")[0];
  }
  return String(error);
}
`
}

